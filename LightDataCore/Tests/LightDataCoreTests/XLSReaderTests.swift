import XCTest
@testable import LightDataCore

/// Regression coverage for the legacy `.xls` (BIFF8) reader. The fixture is a real
/// Excel 97–2003 workbook (first sheet "Sales" with text/int/float/bool/unicode/empty
/// cells plus a long string, and a second sheet that must be ignored), embedded as
/// base64 so the test is self-contained.
final class XLSReaderTests: XCTestCase {
    func testReadsFirstSheetWithMixedCellTypes() throws {
        let data = Data(base64Encoded: Self.fixtureBase64.filter { !$0.isWhitespace })!
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("ld-xls-\(UUID().uuidString).xls")
        try data.write(to: url)
        defer { try? FileManager.default.removeItem(at: url) }

        let table = try XLSReader.readFirstSheet(url: url, firstRowIsHeader: true)

        XCTAssertEqual(table.sheetName, "Sales")
        XCTAssertEqual(table.headers, ["name", "age", "score", "active", "note"])
        XCTAssertEqual(table.rows.count, 4)
        XCTAssertEqual(table.rows[0], ["Alice", "30", "91.5", "true", "vip"])
        XCTAssertEqual(table.rows[1], ["Bob", "25", "80", "false", ""])
        XCTAssertEqual(table.rows[2], ["Carol", "28", "73.25", "true", "新人"])
        XCTAssertEqual(table.rows[3][0], "Dave")
        XCTAssertEqual(table.rows[3][1], "40")
        XCTAssertEqual(table.rows[3][4].count, 50) // long string read whole
    }

    func testRejectsNonOLE2File() {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("ld-not-xls-\(UUID().uuidString).xls")
        try? "a,b,c\n1,2,3\n".data(using: .utf8)!.write(to: url)
        defer { try? FileManager.default.removeItem(at: url) }
        XCTAssertThrowsError(try XLSReader.readFirstSheet(url: url))
    }

